/** A sponsor's mark, in `currentColor` so it takes the ink of whatever it
 *  sits on. Daytona's is the logotype (glyph and wordmark) from its site;
 *  Induction's site sets its name in Helvetica Neue, with no other mark. */
export function SponsorMark({ name }: { name: string }) {
  if (name === "Daytona") return <DaytonaLogotype />;
  return <span className="cc-wordmark-induction">{name}</span>;
}

